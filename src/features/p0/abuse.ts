/**
 * 욕설 거르기.
 *
 * ── 무엇을 막고, 무엇을 **못 막는지** ──────────────────────
 *
 * 막는다: 욕설·비속어. 글자만 보면 알 수 있는 것이다.
 *
 * 못 막는다: **문맥 비방.** "○○병원 불친절해요"에는 욕설이 한 글자도 없다.
 * 기계가 가릴 수 없고, 가리려고 하면 정상적인 후기까지 막힌다 — 이 서비스는
 * "가보니 어땠나요"를 묻는 곳이라 그 쪽 손해가 훨씬 크다. 그건 신고 → 격리가
 * 맡는다(`20261001_report_autoquarantine`).
 *
 * 그래서 화면에도 "절대 막는다"고 쓰지 않는다. 작성창의 문구는
 * "올릴 수 없습니다"까지다 — 실제로 통과하는 글이 있는데 "차단됩니다"라고 적으면
 * 읽는 사람에게 거짓이 된다. **문구가 억제력의 대부분이다.** 쓰려다 보고 멈추게
 * 하는 것이 목적이고, 이 파일은 그 문구를 거짓말로 만들지 않을 만큼만 받친다.
 *
 * ── 왜 공백을 지우지 않는가 ─────────────────────────────────
 * "ㅅ ㅂ" 같은 우회를 잡으려고 공백을 전부 지우고 싶어진다. 그러면 **멀쩡한 글이
 * 막힌다** — "발병 신고"가 "발병신고"가 되어 '병신'에 걸리고, "새끼 손가락"이
 * '새끼'에 걸린다. 의료 글에서 실제로 나오는 말이다. 그래서 공백은 그대로 두고,
 * 대신 같은 글자 반복(ㅅㅅㅅㅂ)과 사이에 끼운 기호(시*발)만 지운다.
 *
 * 놓치는 것이 있다는 전제로 만든다. 첫 번째 체다 — 작정하고 우회하는 것은 신고가
 * 맡는다. 거르지 못한 것보다 **멀쩡한 글을 막는 것**을 더 큰 손해로 본다.
 */

export interface AbuseFinding {
  /** 걸린 표현. 그대로 보여 준다 — 무엇을 지워야 하는지 알아야 고친다. */
  matched: string;
  message: string;
}

/**
 * 글자 사이에 끼울 수 있는 기호. 공백은 **넣지 않는다**(위 주석).
 * "시*발", "시.발", "시-발" 은 잡고 "발병 신고" 는 통과시킨다.
 */
const GAP = "[^\\p{L}\\p{N}\\s]{0,2}";

/**
 * 욕설 목록.
 *
 * 고를 때의 규칙 셋:
 *   · 멀쩡한 낱말에 들어가는 조각은 **넣지 않거나 뒤를 막는다.**
 *     '시발' → 시발점·시발역이 있다. '새끼' → 새끼손가락이 있다.
 *   · 한 글자 자모(ㅄ·ㅅㅂ)는 그 자체로 쓰일 일이 없는 것만.
 *   · 세기가 약한 말(짜증·최악)은 넣지 않는다. 그건 후기이지 욕이 아니다.
 *
 * 각 항목은 정규식 조각이다. `GAP` 으로 이어 붙여 기호 우회를 받는다.
 */
const WORDS: { parts: string[]; not?: string }[] = [
  // 씨발 계열
  { parts: ["씨", "발"] },
  { parts: ["씨", "빨"] },
  { parts: ["씨", "팔"] },
  { parts: ["씨", "바", "알"] },
  { parts: ["시", "발"], not: "점|역|차|탄|식" }, // 시발점·시발역
  { parts: ["시", "팔"] },
  { parts: ["쉬", "발"] },
  { parts: ["슈", "발"] },
  { parts: ["ㅅ", "ㅂ"] },
  { parts: ["ㅆ", "ㅂ"] },
  // 병신 계열
  { parts: ["병", "신"], not: "고|청|자|호" }, // 발병 신고(공백)·병신고는 통과
  { parts: ["븅", "신"] },
  { parts: ["빙", "신"] },
  { parts: ["ㅄ"] },
  { parts: ["ㅂ", "ㅅ"] },
  // 지랄 계열
  { parts: ["지", "랄"] },
  { parts: ["지", "럴"] },
  { parts: ["ㅈ", "ㄹ"] },
  // 좆 계열
  { parts: ["좆"] },
  { parts: ["존", "나"] },
  { parts: ["졸", "라"] },
  // 개/새끼 계열
  { parts: ["개", "새", "끼"] },
  { parts: ["개", "색", "히"] },
  { parts: ["개", "같"] },
  { parts: ["새", "끼"], not: "손|발" }, // 새끼손가락·새끼발가락
  { parts: ["썅"] },
  { parts: ["쌍", "놈"] },
  { parts: ["쌍", "년"] },
  // 사람을 가리키는 비하
  { parts: ["미", "친", "놈"] },
  { parts: ["미", "친", "년"] },
  { parts: ["또", "라", "이"] },
  { parts: ["등", "신"] },
  { parts: ["머", "저", "리"] },
  { parts: ["니", "미"] },
  { parts: ["느", "금"] },
  { parts: ["엠", "창"] },
  { parts: ["ㅈ", "같"] },
  { parts: ["꺼", "져"] },
];

const RULES = WORDS.map(({ parts, not }) => ({
  pattern: new RegExp(parts.join(GAP) + (not ? `(?!${not})` : ""), "u"),
}));

/**
 * 같은 문자 반복을 둘로 줄인다. 노리는 것은 **끼운 기호를 길게 늘인 경우**다 —
 * "시!!!!발" 은 GAP(기호 2개까지) 밖이지만 줄이면 안으로 들어온다.
 *
 * 글자를 끼운 것("씨이이이발")은 잡지 못한다. 잡으려면 모음을 지우고 봐야 하는데
 * 그러면 멀쩡한 낱말이 부서지고 오탐이 는다 — 여기까지가 첫 번째 체다.
 * 둘까지 남기는 것은 "쌍쌍" 처럼 반복이 뜻인 말을 망가뜨리지 않기 위해서다.
 */
function normalize(text: string): string {
  return text.replace(/(.)\1{2,}/gu, "$1$1");
}

/**
 * 첫 번째로 걸린 것을 돌려준다. 여러 개를 한 번에 알려 주지 않는다 —
 * 급한 사람에게 목록을 읽히는 것보다 하나를 고치게 하는 편이 빠르다(원칙 5).
 *
 * `matched` 는 **원문에서 잘라낸 그대로**다. 정규화한 문자열을 보여 주면
 * 자기가 쓴 적 없는 글자를 보게 된다.
 */
export function findAbuse(text: string): AbuseFinding | null {
  const normalized = normalize(text);
  for (const rule of RULES) {
    const hit = rule.pattern.exec(normalized);
    if (hit) {
      return {
        matched: hit[0],
        message: `'${hit[0]}' 은(는) 올릴 수 없습니다. 그 표현을 빼고 다시 올려 주세요.`,
      };
    }
  }
  return null;
}
