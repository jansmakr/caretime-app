import { hasPhoneNumber } from "@/features/p0/pii";

/**
 * 올리기 직전의 확인 — **딱 두 가지만** 묻는다.
 *
 *   phone      전화번호가 적혀 있다
 *   diagnosis  진단·치료 판단을 묻고 있다
 *
 * ── 왜 둘뿐인가 (2026-10-18) ────────────────────────────────
 * 작성창 위아래에 "하지 마세요" 문장이 다섯 줄 있었다. 첫 글을 쓰려는 사람이 그것을
 * 다 읽고 손이 멈췄고, 정작 걸리는 글을 쓴 사람은 읽지 않았다. 그래서 문장을 줄이고
 * **걸릴 때만** 그 자리에서 묻는다.
 *
 * 둘을 고른 이유:
 *   · 전화번호 — 한 번 올라가면 읽힌 것을 되돌릴 수 없다. 서버가 막지만(features/p0/pii)
 *     거절 문구는 쓴 뒤에야 나온다. 미리 지우는 길을 준다
 *   · 진단 요구 — 글을 읽는 사람은 의사가 아니다. 여기서 답을 기다리는 동안 늦어질 수
 *     있는 사람에게 전화·119 를 먼저 보여 준다
 *
 * 욕설·비방은 여기서 묻지 않는다. 서버가 거르고 거절 이유를 그대로 보여 준다.
 *
 * **막지 않는다.** 둘 다 "그대로 올리기"가 있다. 이 판정은 낱말로 하는 짐작이라
 * 틀릴 수 있고, 틀린 짐작이 글을 막으면 묻는 사람이 나간다. 전화번호는 서버가 다시
 * 본다 — 병원 대표번호는 통과하고 개인 번호는 거절된다.
 */
export type ComposeCheck = "phone" | "diagnosis";

/**
 * 진단·치료 판단을 **묻는** 말. 알리는 글("꿰매고 왔어요")은 걸리지 않게
 * 묻는 끝맺음과 함께 있을 때만 잡는다.
 */
const DIAGNOSIS_ASK: RegExp[] = [
  /진단(해|을|좀|받을\s*수)/,
  /(무슨|어떤)\s*병(이|인|일)/,
  /병(인가요|일까요|인지)/,
  /(꿰매|봉합해|꿰메)야\s*(하|할|되|돼)/,
  /(응급실|병원|큰\s*병원)\s*(에\s*)?(가야|가\s*봐야|가봐야)\s*(하|할|되|돼)/,
  /(먹여도|먹어도|발라도|붙여도|써도|줘도)\s*(되|될|돼|괜찮)/,
  /(괜찮|심각한|위험한)(을까요|은가요|은\s*건가요|나요|걸까요|건가요|가요)/,
  /흉터.*(남을까|남나요|안\s*남|남아요\?)/,
  /(어떻게|뭘)\s*(해야|하면)\s*(하|할|되|돼|좋)/,
];

export function checkBeforeSend(body: string): ComposeCheck | null {
  if (hasPhoneNumber(body)) return "phone";
  if (DIAGNOSIS_ASK.some((pattern) => pattern.test(body))) return "diagnosis";
  return null;
}
